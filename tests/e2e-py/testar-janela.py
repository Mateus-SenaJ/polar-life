#!/usr/bin/env python3
"""Teste em navegador: janela não quadrada (Retro Pocket, Instax Mini, Square e Wide) no Quadro e na T-07 (etapa 25) + atalhos de medida (etapa 26).
Uso: python3 tests/e2e-py/testar-janela.py"""
import subprocess, sys, time, pathlib
from playwright.sync_api import sync_playwright
RAIZ = pathlib.Path(__file__).resolve().parents[2] / "site"
PORTA = 8793; BASE = f"http://localhost:{PORTA}"
srv = subprocess.Popen([sys.executable, "-m", "http.server", str(PORTA)], cwd=RAIZ, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
time.sleep(1.2); falhas = []; erros = []
def ok(c, m):
    print(("ok    " if c else "FALHA ") + m)
    if not c: falhas.append(m)
try:
    with sync_playwright() as p:
        b = p.chromium.launch(); pg = b.new_page(viewport={"width": 1440, "height": 900})
        pg.on("pageerror", lambda e: erros.append(str(e)))
        pg.goto(BASE + "/app/editor/quadro/#foto-3"); pg.wait_for_timeout(400)
        pg.click("#tab-molduras"); pg.wait_for_timeout(100)
        for fid, w, h, jw, jh in [("pocket", 60, 80, 48, 60), ("imini", 54, 86, 46, 62), ("isq", 72, 86, 62, 62), ("iwide", 108, 86, 99, 62)]:
            ok(pg.is_enabled(f'[data-fmt="{fid}"]'), f"{fid}: botão ativo")
            pg.click(f'[data-fmt="{fid}"]'); pg.click("#fmt-sim"); pg.wait_for_timeout(150)
            fr = pg.evaluate("PLQ.ST()[0].fr")
            ok(fr["w"] == w and fr["h"] == h and fr["jh"] == jh, f"{fid}: moldura {fr['w']}×{fr['h']}, janela alta {fr['jh']}")
            r = pg.evaluate("(()=>{var a=document.getElementById('win').getBoundingClientRect();return a.width/a.height})()")
            ok(abs(r - jw / jh) < .02, f"{fid}: janela na tela com proporção {r:.3f} (esperado {jw/jh:.3f})")
            ok(pg.input_value("#mo-jh").replace(",", ".") == str(jh) and pg.input_value("#mo-jw").replace(",", ".") == str(jw), f"{fid}: campos largura e altura da janela")
            ok(pg.evaluate("PLQ.FR.jh") == jh and pg.evaluate("PLQ.FR.jw") == jw, f"{fid}: PLQ.FR atualizado")
            cob = pg.evaluate("(()=>{var w=document.getElementById('win').getBoundingClientRect(),f=document.querySelector('#clip .ph').getBoundingClientRect();return f.left<=w.left+1&&f.right>=w.right-1&&f.top<=w.top+1&&f.bottom>=w.bottom-1})()")
            ok(cob, f"{fid}: foto cobre a janela")
        pg.evaluate("(()=>{var s=PLQ.S();s.ang=10;PLQ.commit('t')})()"); pg.wait_for_timeout(100)
        ok(pg.evaluate("PLQ.S().z") > 100, "janela larga: endireitar sobe o zoom mínimo")
        pg.focus("#win"); pg.keyboard.press("ArrowDown"); pg.wait_for_timeout(80)
        ok(abs(pg.evaluate("PLQ.S().py")) <= 0.5, "seta move sem sair da janela")
        # etapa 26: atalhos de personalização (proporção da janela, faixa inferior, margens, cantos)
        pg.click('[data-fmt="classico"]'); pg.click("#fmt-sim"); pg.wait_for_timeout(150)
        def pre(k, i): pg.click(f'[data-pre="{k}"][data-i="{i}"]'); pg.wait_for_timeout(120)
        pre(0, 1)  # 4:5
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(fr["fmt"] == "pers" and abs(fr["jh"] - 95) < .06 and abs(fr["h"] - 126) < .06, f"atalho 4:5: janela 76×{fr['jh']}, altura externa {fr['h']}")
        ok(pg.get_attribute('[data-pre="0"][data-i="1"]', "aria-pressed") == "true" and pg.get_attribute('[data-pre="0"][data-i="0"]', "aria-pressed") == "false", "atalho 4:5 marcado (aria-pressed) e 1:1 não")
        ok(pg.is_visible('[data-pre="0"][data-i="1"] svg'), "atalho marcado mostra o ícone de check (não só cor)")
        r = pg.evaluate("(()=>{var a=document.getElementById('win').getBoundingClientRect();return a.width/a.height})()"); ok(abs(r - .8) < .02, f"janela na tela 4:5 ({r:.3f})")
        pre(0, 7)  # 16:9
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(abs(fr["jh"] - 42.75) < .06, f"atalho 16:9: janela 76×{fr['jh']}")
        pre(1, 0)  # faixa inferior fina
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(abs(fr["h"] - fr["topo"] - fr["jh"] - 12) < .06, "faixa inferior Fina = 12 mm")
        pre(2, 3)  # margens largas 9: com a faixa fina (12) a conta dá 9 < 10 mm e o atalho mostra erro, sem gravar
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(fr["lado"] == 6 and pg.is_visible('[data-k="bt"] .f__h'), "margens Larga com faixa Fina: erro na faixa inferior e nada gravado")
        pre(1, 2); pre(2, 3)  # faixa Clássica (25) e margens Larga (9)
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(fr["lado"] == 9 and fr["topo"] == 9, "margens Larga = 9 mm (lateral e superior)")
        pre(3, 3)  # cantos redondos
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(fr["rad"] == 3, "cantos Redondo = 3 mm")
        pg.evaluate("PLQ.ST()[0].fr.lock=false"); pg.click('[data-fmt="classico"]'); pg.click("#fmt-sim"); pg.wait_for_timeout(120)
        cob = pg.evaluate("(()=>{var w=document.getElementById('win').getBoundingClientRect(),f=document.querySelector('#clip .ph').getBoundingClientRect();return f.left<=w.left+1&&f.right>=w.right-1&&f.top<=w.top+1&&f.bottom>=w.bottom-1})()")
        ok(cob, "depois dos atalhos a foto continua cobrindo a janela")
        pre(0, 6)  # 3:2 em Clássico, depois desfazer
        pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
        ok(pg.evaluate("PLQ.ST()[0].fr.fmt") == "classico", "desfazer volta o atalho")
        pg.set_viewport_size({"width": 390, "height": 800}); pg.wait_for_timeout(150)
        ok(pg.evaluate("document.documentElement.scrollWidth<=window.innerWidth+1"), "390 px: sem rolagem horizontal com os atalhos")
        ok(pg.evaluate("[].slice.call(document.querySelectorAll('.pre__b')).every(function(b){return b.getBoundingClientRect().height>=43.5||b.offsetParent===null})"), "atalhos com 44 px ou mais de altura")
        pg.set_viewport_size({"width": 1440, "height": 900})
        pg.click("#mo-reset"); pg.wait_for_timeout(150)
        fr = pg.evaluate("PLQ.ST()[0].fr"); ok(fr["fmt"] == "classico" and fr["jh"] == 76, "Resetar formato volta ao Clássico com janela 76")
        bt0 = pg.evaluate("PLQ.ST()[0].fr.h-PLQ.ST()[0].fr.topo-PLQ.ST()[0].fr.jh")
        pg.fill("#mo-jh", "60"); pg.keyboard.press("Tab"); pg.wait_for_timeout(120)
        fr = pg.evaluate("PLQ.ST()[0].fr")
        ok(fr["fmt"] == "pers" and fr["jh"] == 60 and abs(fr["h"] - fr["topo"] - 60 - bt0) < .02, "editar altura da janela: Personalizado, faixa inferior mantida")
        pg.fill("#mo-jh", "10"); pg.keyboard.press("Tab"); pg.wait_for_timeout(100)
        ok(pg.is_visible('[data-k="jh"] .f__h'), "altura da janela abaixo do mínimo mostra erro")
        # etapa 27: orientação (Vertical/Horizontal, atalho R)
        pg.click("#mo-reset"); pg.wait_for_timeout(150)
        ok(pg.get_attribute('[data-ori="v"]', "aria-pressed") == "true" and pg.get_attribute('[data-ori="h"]', "aria-pressed") == "false", "orientação: Vertical marcada por padrão")
        pg.click('[data-ori="h"]'); pg.wait_for_timeout(200)
        R = pg.evaluate("(()=>{var r=PLQ.FR;return{w:r.w,h:r.h,lado:r.lado,ladoD:r.ladoD,topo:r.topo,jw:r.jw,jh:r.jh,ori:r.ori,cw:r.cw,ch:r.ch}})()")
        ok(R["ori"] == "h" and R["w"] == 107 and R["h"] == 88 and R["lado"] == 25 and R["ladoD"] == 6 and R["topo"] == 6 and R["jw"] == 76 and R["jh"] == 76 and R["cw"] == 88 and R["ch"] == 107, f"Horizontal: moldura {R['w']}×{R['h']}, faixa grossa à esquerda ({R['lado']} mm)")
        ok(pg.evaluate("document.getElementById('pq').classList.contains('is-h')"), "Horizontal: quadro com classe is-h")
        ok(pg.get_attribute('[data-ori="h"]', "aria-pressed") == "true" and pg.is_visible('[data-ori="h"] svg'), "Horizontal marcado com check")
        g = pg.evaluate("(()=>{var q=document.getElementById('pq').getBoundingClientRect(),w=document.getElementById('win').getBoundingClientRect();return{r:q.width/q.height,esq:(w.left-q.left)/q.width,dir:(q.right-w.right)/q.width}})()")
        ok(abs(g["r"] - 107 / 88) < .02, f"Horizontal: moldura na tela com proporção {g['r']:.3f}")
        ok(abs(g["esq"] - 25 / 107) < .01 and abs(g["dir"] - 6 / 107) < .01, f"Horizontal: faixa esquerda {g['esq']*107:.1f} mm, direita {g['dir']*107:.1f} mm")
        lg = pg.evaluate("(()=>{var q=document.getElementById('pq').getBoundingClientRect(),b=document.getElementById('cap-band').getBoundingClientRect();return(b.left+b.width/2-q.left)/q.width})()")
        ok(lg < .25, "Horizontal: legenda fica na faixa grossa, à esquerda")
        ok("lateral" in pg.text_content("#cota"), "Horizontal: cota diz «Passe-partout lateral»")
        cob = pg.evaluate("(()=>{var w=document.getElementById('win').getBoundingClientRect(),f=document.querySelector('#clip .ph').getBoundingClientRect();return f.left<=w.left+1&&f.right>=w.right-1&&f.top<=w.top+1&&f.bottom>=w.bottom-1})()")
        ok(cob, "Horizontal: foto cobre a janela")
        ok(pg.input_value("#mo-w").replace(",", ".") == "88", "Horizontal: campos de medida seguem os da polaroid em pé")
        pg.screenshot(path="/tmp/quadro-h.png")
        pg.click("body", position={"x": 5, "y": 5}); pg.keyboard.press("r"); pg.wait_for_timeout(150)
        ok(pg.evaluate("PLQ.ST()[0].fr.ori") == "v", "atalho R volta para Vertical")
        pg.keyboard.press("r"); pg.wait_for_timeout(150)
        ok(pg.evaluate("PLQ.ST()[0].fr.ori") == "h", "atalho R gira para Horizontal")
        pg.keyboard.press("Control+z"); pg.wait_for_timeout(150)
        ok(pg.evaluate("PLQ.ST()[0].fr.ori") == "v", "desfazer volta a orientação")
        pg.click('[data-fmt="iwide"]'); pg.click("#fmt-sim"); pg.wait_for_timeout(150)
        pg.click('[data-ori="h"]'); pg.wait_for_timeout(200)
        r = pg.evaluate("(()=>{var a=document.getElementById('win').getBoundingClientRect();return a.width/a.height})()")
        ok(abs(r - 62 / 99) < .02, f"Instax Wide horizontal: janela com proporção {r:.3f}")
        pg.click('[data-ori="v"]'); pg.wait_for_timeout(150)
        pg.set_viewport_size({"width": 390, "height": 800}); pg.wait_for_timeout(150)
        ok(pg.evaluate("document.documentElement.scrollWidth<=window.innerWidth+1"), "390 px: sem rolagem horizontal com a orientação")
        pg.set_viewport_size({"width": 1440, "height": 900})
        pg.click("#mo-reset"); pg.wait_for_timeout(150)
        pg.click('[data-fmt="iwide"]'); pg.click("#fmt-sim"); pg.wait_for_timeout(150)
        pg.goto(BASE + "/app/editor/"); pg.wait_for_timeout(500)
        d = pg.evaluate("(()=>{var e=document.querySelector('.pol__ph').getBoundingClientRect();return e.width/e.height})()")
        d = max(d, 1 / d)   # a polaroid larga entra girada na folha A4 em pé
        ok(abs(d - 99 / 62) < .03, f"T-07: janela da polaroid com proporção {d:.3f}")
        ok(not erros, "sem erro de script " + str(erros))
        b.close()
finally:
    srv.terminate()
print("\n✖ %d falha(s)" % len(falhas) if falhas else "\n✔ Janela não quadrada: sem falhas"); sys.exit(1 if falhas else 0)
